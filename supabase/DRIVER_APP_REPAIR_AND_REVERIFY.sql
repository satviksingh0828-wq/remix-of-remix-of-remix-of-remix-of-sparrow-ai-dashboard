-- Garuda Driver's App: ONE-TIME REPAIR + RE-VERIFY
-- Run this entire file once in the Supabase SQL Editor.
-- Safe to run again: it uses create/alter-if-not-exists and create-or-replace.
-- It intentionally ends links for closed/non-own trips and keeps only the newest
-- active link or QR row if legacy duplicate records exist.

create extension if not exists pgcrypto;

do $$
begin
  if to_regclass('public.trips') is null then
    raise exception 'The public.trips table is missing. Run the main Sparrow database setup first.';
  end if;
end;
$$;

-- 1. Create or repair the Driver App tables and required columns.
create table if not exists public.driver_trip_qr_tokens (
  id uuid primary key default gen_random_uuid(),
  trip_id uuid not null references public.trips(id) on delete cascade,
  token text,
  token_hash text not null unique,
  expires_at timestamptz,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.driver_trip_qr_tokens add column if not exists token text;
alter table public.driver_trip_qr_tokens add column if not exists token_hash text;
alter table public.driver_trip_qr_tokens add column if not exists expires_at timestamptz;
alter table public.driver_trip_qr_tokens add column if not exists used_at timestamptz;
alter table public.driver_trip_qr_tokens add column if not exists created_at timestamptz not null default now();
alter table public.driver_trip_qr_tokens alter column expires_at drop not null;

create table if not exists public.driver_trip_links (
  id uuid primary key default gen_random_uuid(),
  trip_id uuid not null references public.trips(id) on delete cascade,
  device_id text not null,
  session_token_hash text not null unique,
  linked_at timestamptz not null default now(),
  last_seen_at timestamptz,
  ended_at timestamptz
);

alter table public.driver_trip_links add column if not exists device_id text;
alter table public.driver_trip_links add column if not exists session_token_hash text;
alter table public.driver_trip_links add column if not exists linked_at timestamptz not null default now();
alter table public.driver_trip_links add column if not exists last_seen_at timestamptz;
alter table public.driver_trip_links add column if not exists ended_at timestamptz;

create table if not exists public.driver_trip_locations (
  id bigint generated by default as identity primary key,
  link_id uuid not null references public.driver_trip_links(id) on delete cascade,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_m double precision check (accuracy_m is null or accuracy_m >= 0),
  recorded_at timestamptz not null default now()
);

alter table public.driver_trip_locations add column if not exists accuracy_m double precision;
alter table public.driver_trip_locations add column if not exists recorded_at timestamptz not null default now();

-- 2. Normalize legacy QR and active-link data before enforcing unique indexes.
delete from public.driver_trip_qr_tokens q
where q.id in (
  select id
  from (
    select id, row_number() over (partition by trip_id order by created_at desc nulls last, id desc) as row_number
    from public.driver_trip_qr_tokens
  ) duplicates
  where row_number > 1
);

update public.driver_trip_qr_tokens
set token = encode(gen_random_bytes(32), 'hex')
where token is null or trim(token) = '';

with duplicate_tokens as (
  select id,
         row_number() over (partition by token order by created_at desc nulls last, id desc) as row_number
  from public.driver_trip_qr_tokens
)
update public.driver_trip_qr_tokens q
set token = encode(gen_random_bytes(32), 'hex')
from duplicate_tokens d
where q.id = d.id
  and d.row_number > 1;

update public.driver_trip_qr_tokens
set token_hash = encode(digest(token, 'sha256'), 'hex'),
    expires_at = null;

-- A legacy link without a session hash cannot be recovered securely. Give it an
-- unusable random hash so the device can claim a fresh active session.
update public.driver_trip_links
set device_id = coalesce(nullif(trim(device_id), ''), 'legacy-' || id::text),
    session_token_hash = coalesce(nullif(trim(session_token_hash), ''), encode(digest(id::text || clock_timestamp()::text || random()::text, 'sha256'), 'hex')),
    linked_at = coalesce(linked_at, now())
where device_id is null
   or trim(device_id) = ''
   or session_token_hash is null
   or trim(session_token_hash) = ''
   or linked_at is null;

with duplicate_session_hashes as (
  select id,
         row_number() over (partition by session_token_hash order by coalesce(last_seen_at, linked_at) desc, linked_at desc, id desc) as row_number
  from public.driver_trip_links
)
update public.driver_trip_links l
set session_token_hash = encode(gen_random_bytes(32), 'hex')
from duplicate_session_hashes d
where l.id = d.id
  and d.row_number > 1;

-- Only the newest active device is retained for each trip.
with ranked_active_links as (
  select id,
         row_number() over (partition by trip_id order by coalesce(last_seen_at, linked_at) desc, linked_at desc, id desc) as row_number
  from public.driver_trip_links
  where ended_at is null
)
update public.driver_trip_links l
set ended_at = now(),
    last_seen_at = coalesce(l.last_seen_at, now())
from ranked_active_links r
where l.id = r.id
  and r.row_number > 1;

-- Driver linkage is limited to own-vehicle trips; an entered end date does not revoke access.
update public.driver_trip_links l
set ended_at = now(),
    last_seen_at = coalesce(l.last_seen_at, now())
from public.trips t
where t.id = l.trip_id
  and l.ended_at is null
  and t.ownership <> 'own';

delete from public.driver_trip_qr_tokens q
using public.trips t
where t.id = q.trip_id
  and t.ownership <> 'own';

alter table public.driver_trip_qr_tokens alter column token set not null;
alter table public.driver_trip_qr_tokens alter column token_hash set not null;
alter table public.driver_trip_links alter column device_id set not null;
alter table public.driver_trip_links alter column session_token_hash set not null;

create unique index if not exists driver_trip_qr_tokens_one_per_trip_idx
  on public.driver_trip_qr_tokens (trip_id);
create unique index if not exists driver_trip_qr_tokens_token_idx
  on public.driver_trip_qr_tokens (token);
create unique index if not exists driver_trip_qr_tokens_token_hash_idx
  on public.driver_trip_qr_tokens (token_hash);
create index if not exists driver_trip_qr_tokens_trip_idx
  on public.driver_trip_qr_tokens (trip_id, created_at desc);
create unique index if not exists driver_trip_links_one_active_device_idx
  on public.driver_trip_links (trip_id) where ended_at is null;
create unique index if not exists driver_trip_links_session_hash_idx
  on public.driver_trip_links (session_token_hash);
create index if not exists driver_trip_links_trip_idx
  on public.driver_trip_links (trip_id, ended_at, last_seen_at desc);
create index if not exists driver_trip_locations_link_time_idx
  on public.driver_trip_locations (link_id, recorded_at desc);

alter table public.driver_trip_qr_tokens enable row level security;
alter table public.driver_trip_links enable row level security;
alter table public.driver_trip_locations enable row level security;
alter table public.driver_trip_qr_tokens force row level security;
alter table public.driver_trip_links force row level security;
alter table public.driver_trip_locations force row level security;

revoke all on public.driver_trip_qr_tokens from anon, authenticated;
revoke all on public.driver_trip_links from anon, authenticated;
revoke all on public.driver_trip_locations from anon, authenticated;
grant all on public.driver_trip_qr_tokens to service_role;
grant all on public.driver_trip_links to service_role;
grant all on public.driver_trip_locations to service_role;

-- 3. Recreate the permanent QR, one-device, session, tracking, and live-map RPCs.
create or replace function public.issue_driver_trip_qr(p_trip_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_trip record;
  v_token text;
begin
  select t.id, t.trip_code into v_trip
  from public.trips t
  where t.id = p_trip_id
    and t.ownership = 'own';
  if not found then raise exception 'Only own-vehicle trips can have a Trip QR Code'; end if;

  select token into v_token
  from public.driver_trip_qr_tokens
  where trip_id = v_trip.id
  for update;

  if v_token is null then
    v_token := encode(gen_random_bytes(32), 'hex');
    insert into public.driver_trip_qr_tokens (trip_id, token, token_hash, expires_at)
    values (v_trip.id, v_token, encode(digest(v_token, 'sha256'), 'hex'), null)
    on conflict (trip_id) do update
      set token = excluded.token,
          token_hash = excluded.token_hash,
          expires_at = null;
  else
    update public.driver_trip_qr_tokens
    set token_hash = encode(digest(v_token, 'sha256'), 'hex'), expires_at = null
    where trip_id = v_trip.id;
  end if;

  return jsonb_build_object('token', v_token, 'trip_id', v_trip.id, 'trip_code', v_trip.trip_code, 'stable', true, 'expires_at', null);
end;
$$;

create or replace function public.claim_driver_trip(p_qr_token text, p_device_id text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_qr record;
  v_link record;
  v_session_token text;
  v_link_id uuid;
begin
  if coalesce(trim(p_qr_token), '') = '' or coalesce(trim(p_device_id), '') = '' then
    raise exception 'QR token and device ID are required';
  end if;

  select q.trip_id, t.trip_code into v_qr
  from public.driver_trip_qr_tokens q
  join public.trips t on t.id = q.trip_id
  where q.token_hash = encode(digest(p_qr_token, 'sha256'), 'hex')
    and t.ownership = 'own'
  for update;
  if not found then raise exception 'This Trip QR Code is not linked to an own-vehicle trip'; end if;

  select l.id, l.device_id into v_link
  from public.driver_trip_links l
  where l.trip_id = v_qr.trip_id and l.ended_at is null
  for update;
  if found and v_link.device_id <> p_device_id then
    return jsonb_build_object('status', 'already_linked', 'trip_code', v_qr.trip_code);
  end if;

  v_session_token := encode(gen_random_bytes(32), 'hex');
  if found then
    v_link_id := v_link.id;
    update public.driver_trip_links
    set session_token_hash = encode(digest(v_session_token, 'sha256'), 'hex'), last_seen_at = now()
    where id = v_link_id;
  else
    insert into public.driver_trip_links (trip_id, device_id, session_token_hash, last_seen_at)
    values (v_qr.trip_id, p_device_id, encode(digest(v_session_token, 'sha256'), 'hex'), now())
    returning id into v_link_id;
  end if;

  return jsonb_build_object('status', 'linked', 'session_token', v_session_token, 'link_id', v_link_id, 'trip_id', v_qr.trip_id, 'trip_code', v_qr.trip_code);
exception when unique_violation then
  return jsonb_build_object('status', 'already_linked', 'message', 'Another device connected to this trip first');
end;
$$;

create or replace function public.get_driver_trip(p_session_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_trip record;
  v_trip_id uuid;
  v_link_id uuid;
  v_manifests jsonb;
  v_latest_location jsonb;
begin
  select l.id, l.trip_id into v_link_id, v_trip_id
  from public.driver_trip_links l
  where l.session_token_hash = encode(digest(p_session_token, 'sha256'), 'hex') and l.ended_at is null
  for update;
  if not found then raise exception 'Driver session is not active'; end if;

  select t.id, t.trip_code, t.start_date, t.start_time,
         v.registration_number, v.internal_code, v.nickname, v.manufacturer, v.model,
         d.driver_code, d.full_name, d.mobile_number,
         sl.location_name as source_name, sl.city as source_city, sl.state as source_state,
         el.location_name as destination_name, el.city as destination_city, el.state as destination_state
    into v_trip
  from public.trips t
  left join public.vehicles v on v.id = t.vehicle_id
  left join public.drivers d on d.id = t.driver_id
  left join public.locations sl on sl.id = t.start_location_id
  left join public.locations el on el.id = t.end_location_id
  where t.id = v_trip_id and t.ownership = 'own';

  select coalesce(jsonb_agg(jsonb_build_object(
    'manifest_number', m.manifest_number, 'from_pin_code', m.from_pin_code, 'to_pin_code', m.to_pin_code,
    'weight_kg', m.weight_kg, 'quantity', m.quantity, 'source_name', fl.location_name, 'destination_name', tl.location_name
  ) order by m.created_at), '[]'::jsonb)
  into v_manifests
  from public.trip_manifests m
  left join public.locations fl on fl.id = m.from_location_id
  left join public.locations tl on tl.id = m.to_location_id
  where m.trip_id = v_trip_id;

  select jsonb_build_object('latitude', x.latitude, 'longitude', x.longitude, 'accuracy_m', x.accuracy_m, 'recorded_at', x.recorded_at)
  into v_latest_location
  from public.driver_trip_locations x
  where x.link_id = v_link_id
  order by x.recorded_at desc
  limit 1;

  update public.driver_trip_links set last_seen_at = now() where id = v_link_id;
  return jsonb_build_object(
    'trip', jsonb_build_object(
      'id', v_trip_id, 'trip_code', v_trip.trip_code, 'start_date', v_trip.start_date, 'start_time', v_trip.start_time,
      'source', jsonb_build_object('name', v_trip.source_name, 'city', v_trip.source_city, 'state', v_trip.source_state),
      'destination', jsonb_build_object('name', v_trip.destination_name, 'city', v_trip.destination_city, 'state', v_trip.destination_state),
      'vehicle', jsonb_build_object('registration_number', v_trip.registration_number, 'internal_code', v_trip.internal_code, 'nickname', v_trip.nickname, 'manufacturer', v_trip.manufacturer, 'model', v_trip.model),
      'driver', jsonb_build_object('code', v_trip.driver_code, 'name', v_trip.full_name, 'mobile_number', v_trip.mobile_number),
      'manifests', v_manifests
    ),
    'latest_location', coalesce(v_latest_location, 'null'::jsonb)
  );
end;
$$;

create or replace function public.record_driver_location(
  p_session_token text,
  p_latitude double precision,
  p_longitude double precision,
  p_accuracy_m double precision default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_link_id uuid;
begin
  select id into v_link_id
  from public.driver_trip_links
  where session_token_hash = encode(digest(p_session_token, 'sha256'), 'hex') and ended_at is null;
  if not found then raise exception 'Driver session is not active'; end if;
  insert into public.driver_trip_locations (link_id, latitude, longitude, accuracy_m)
  values (v_link_id, p_latitude, p_longitude, p_accuracy_m);
  update public.driver_trip_links set last_seen_at = now() where id = v_link_id;
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.end_driver_trip(p_session_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_link_id uuid;
begin
  update public.driver_trip_links
  set ended_at = now(), last_seen_at = now()
  where session_token_hash = encode(digest(p_session_token, 'sha256'), 'hex') and ended_at is null
  returning id into v_link_id;
  if not found then raise exception 'Driver session is not active'; end if;
  return jsonb_build_object('ok', true, 'ended_at', now());
end;
$$;

create or replace function public.get_trip_live_location(p_trip_id uuid)
returns jsonb
language sql
security definer
set search_path = public, extensions
as $$
  select case when t.ownership = 'own' then (
    select jsonb_build_object(
      'trip_id', t.id, 'trip_code', t.trip_code, 'latitude', x.latitude, 'longitude', x.longitude,
      'accuracy_m', x.accuracy_m, 'recorded_at', x.recorded_at, 'last_seen_at', l.last_seen_at, 'active', (l.ended_at is null)
    )
    from public.driver_trip_links l
    join public.driver_trip_locations x on x.link_id = l.id
    where l.trip_id = t.id
    order by x.recorded_at desc
    limit 1
  ) else null end
  from public.trips t
  where t.id = p_trip_id;
$$;

