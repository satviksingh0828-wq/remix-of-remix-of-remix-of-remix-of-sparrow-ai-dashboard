-- 4. FINAL RE-VERIFICATION. Every row must show status = OK.
with checks as (
  select 'table: driver_trip_qr_tokens' as check_name,
         to_regclass('public.driver_trip_qr_tokens') is not null as passed,
         'required QR-token table exists' as detail
  union all select 'table: driver_trip_links', to_regclass('public.driver_trip_links') is not null, 'required device-link table exists'
  union all select 'table: driver_trip_locations', to_regclass('public.driver_trip_locations') is not null, 'required GPS table exists'
  union all select 'function: issue_driver_trip_qr', to_regprocedure('public.issue_driver_trip_qr(uuid)') is not null, 'permanent QR issuer exists'
  union all select 'function: claim_driver_trip', to_regprocedure('public.claim_driver_trip(text,text)') is not null, 'claim RPC exists'
  union all select 'function: get_driver_trip', to_regprocedure('public.get_driver_trip(text)') is not null, 'active-session trip lookup exists'
  union all select 'function: record_driver_location', to_regprocedure('public.record_driver_location(text,double precision,double precision,double precision)') is not null, 'GPS recorder exists'
  union all select 'function: end_driver_trip', to_regprocedure('public.end_driver_trip(text)') is not null, 'end-trip RPC exists'
  union all select 'function: get_trip_live_location', to_regprocedure('public.get_trip_live_location(uuid)') is not null, 'live-location RPC exists'
  union all select 'claim returns session_token + link_id',
    position('session_token' in pg_get_functiondef('public.claim_driver_trip(text,text)'::regprocedure)) > 0
    and position('link_id' in pg_get_functiondef('public.claim_driver_trip(text,text)'::regprocedure)) > 0,
    'driver claim response contains the active-session contract'
  union all select 'stable QR rows',
    not exists (
      select 1 from public.driver_trip_qr_tokens
      where token is null or token_hash <> encode(digest(token, 'sha256'), 'hex') or expires_at is not null
    ),
    'every QR token is reusable, hashed, and non-expiring'
  union all select 'one QR per trip',
    not exists (select 1 from public.driver_trip_qr_tokens group by trip_id having count(*) > 1),
    'duplicate QR rows do not exist'
  union all select 'eligible QR trips only',
    not exists (
      select 1 from public.driver_trip_qr_tokens q join public.trips t on t.id = q.trip_id
      where t.ownership <> 'own'
    ),
    'only own-vehicle trips have QR rows'
  union all select 'one active device per trip',
    not exists (select 1 from public.driver_trip_links where ended_at is null group by trip_id having count(*) > 1),
    'active-device conflict is prevented'
  union all select 'active links eligible only',
    not exists (
      select 1 from public.driver_trip_links l join public.trips t on t.id = l.trip_id
      where l.ended_at is null and t.ownership <> 'own'
    ),
    'only own-vehicle trips can have active devices'
  union all select 'location rows valid',
    not exists (
      select 1 from public.driver_trip_locations
      where latitude not between -90 and 90 or longitude not between -180 and 180 or (accuracy_m is not null and accuracy_m < 0)
    ),
    'stored GPS coordinates pass integrity checks'
)
select check_name,
       case when passed then 'OK' else 'REPAIR NEEDED' end as status,
       detail
from checks
order by check_name;
