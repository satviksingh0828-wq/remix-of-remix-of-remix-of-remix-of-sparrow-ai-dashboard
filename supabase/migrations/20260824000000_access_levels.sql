-- Access Levels — safe, idempotent Supabase setup
-- Run once in the Supabase SQL Editor. Existing app_users and access are preserved.
begin;

-- The UI calls the existing `viewer` role "Manager". Keep the stored value so
-- existing accounts and signed sessions remain compatible.
do $$
declare constraint_name text;
begin
  select conname into constraint_name
  from pg_constraint
  where conrelid = 'public.app_users'::regclass and contype = 'c'
    and pg_get_constraintdef(oid) ilike '%role%';
  if constraint_name is not null then
    execute format('alter table public.app_users drop constraint %I', constraint_name);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'app_users_role_check' and conrelid = 'public.app_users'::regclass) then
    alter table public.app_users add constraint app_users_role_check check (role in ('admin', 'viewer', 'basic'));
  end if;
end $$;

create table if not exists public.access_scopes (
  scope_key text primary key,
  module text not null,
  label text not null,
  description text not null default '',
  branch_aware boolean not null default false,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.role_permissions (
  role text not null check (role in ('admin', 'viewer', 'basic')),
  scope_key text not null references public.access_scopes(scope_key) on update cascade on delete cascade,
  action text not null check (action in ('read','create','update','delete','approve','close','reopen','import','export','manage')),
  allowed boolean not null default false,
  branch_mode text not null default 'none' check (branch_mode in ('all','assigned','none')),
  updated_by uuid references public.app_users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (role, scope_key, action)
);

create table if not exists public.user_permission_overrides (
  user_id uuid not null references public.app_users(id) on delete cascade,
  scope_key text not null references public.access_scopes(scope_key) on update cascade on delete cascade,
  action text not null check (action in ('read','create','update','delete','approve','close','reopen','import','export','manage')),
  effect text not null check (effect in ('allow','deny')),
  branch_mode text not null default 'none' check (branch_mode in ('all','assigned','none')),
  updated_by uuid references public.app_users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (user_id, scope_key, action)
);

create table if not exists public.user_scope_branches (
  user_id uuid not null references public.app_users(id) on delete cascade,
  scope_key text not null references public.access_scopes(scope_key) on update cascade on delete cascade,
  branch_id uuid not null references public.branches(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, scope_key, branch_id)
);

create table if not exists public.permission_change_logs (
  id bigint generated by default as identity primary key,
  changed_by uuid references public.app_users(id) on delete set null,
  target_role text check (target_role in ('admin', 'viewer', 'basic')),
  target_user_id uuid references public.app_users(id) on delete set null,
  scope_key text not null,
  action text not null,
  allowed boolean not null,
  branch_mode text not null,
  created_at timestamptz not null default now()
);

-- These security-control tables are service-role only. The application updates
-- them through HMAC-token-verified server functions; never from the browser.
alter table public.access_scopes enable row level security;
alter table public.role_permissions enable row level security;
alter table public.user_permission_overrides enable row level security;
alter table public.user_scope_branches enable row level security;
alter table public.permission_change_logs enable row level security;
grant all on public.access_scopes, public.role_permissions, public.user_permission_overrides,
  public.user_scope_branches, public.permission_change_logs to service_role;
revoke all on public.access_scopes, public.role_permissions, public.user_permission_overrides,
  public.user_scope_branches, public.permission_change_logs from anon, authenticated;

