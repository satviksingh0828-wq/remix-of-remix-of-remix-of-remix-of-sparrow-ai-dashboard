-- Seed only missing rows. Re-running this script never overwrites an admin's choices.
with actions(action) as (values ('read'),('create'),('update'),('delete'),('approve'),('close'),('reopen'),('import'),('export'),('manage')),
roles(role) as (values ('admin'),('viewer'),('basic'))
insert into public.role_permissions(role,scope_key,action,allowed,branch_mode)
select r.role, s.scope_key, a.action,
  case
    when r.role='admin' then true
    when r.role='viewer' then a.action in ('read','export') and (
      s.scope_key like 'operations.%' and s.scope_key not in ('operations.monthly_mis','operations.import')
      or s.scope_key in ('masters.vehicles','masters.drivers','masters.transporters','masters.locations')
      or s.scope_key like 'hr.%' or s.scope_key like 'dashboard.%' or s.scope_key like 'reports.%'
      or s.scope_key='notifications')
    when r.role='basic' then s.scope_key in (
      'operations.monthly_mis','operations.trips','operations.income','operations.expenditure',
      'operations.driver_payroll','reports.booking','masters.drivers','masters.transporters')
  end,
  case when not s.branch_aware then 'none' when r.role='basic' then 'assigned' else 'all' end
from roles r cross join public.access_scopes s cross join actions a
on conflict (role,scope_key,action) do nothing;

create index if not exists role_permissions_scope_idx on public.role_permissions(scope_key);
create index if not exists user_permission_overrides_user_idx on public.user_permission_overrides(user_id);
create index if not exists user_scope_branches_user_idx on public.user_scope_branches(user_id);
create index if not exists permission_change_logs_created_idx on public.permission_change_logs(created_at desc);

commit;
