select '01_required_tables' as check_name,
  case when count(*) = 5 then 'OK' else 'MISSING: ' || (5-count(*))::text end as status,
  count(*)::text || '/5 tables present' as details
from information_schema.tables
where table_schema='public' and table_name in (
  'access_scopes','role_permissions','user_permission_overrides',
  'user_scope_branches','permission_change_logs'
);

select '02_role_values' as check_name,
  case when count(*) filter (where role not in ('admin','viewer','basic')) = 0
    then 'OK' else 'INVALID ROLE DATA' end as status,
  count(*)::text || ' users checked' as details
from public.app_users;

select '03_scope_catalogue' as check_name,
  case when count(*) >= 73 then 'OK' else 'MISSING SCOPES' end as status,
  count(*)::text || '/73 required scopes installed' as details
from public.access_scopes where is_active=true;

select '04_permission_matrix' as check_name,
  case when count(*) = (select count(*) * 3 * 10 from public.access_scopes)
    then 'OK' else 'MISSING PERMISSION ROWS' end as status,
  count(*)::text || '/' || (select (count(*) * 3 * 10)::text from public.access_scopes) || ' rows present' as details
from public.role_permissions;

select '05_admin_defaults' as check_name,
  case when count(*) filter (where not allowed) = 0 then 'OK' else 'ADMIN RIGHTS CUSTOMIZED' end as status,
  count(*) filter (where allowed)::text || '/' || count(*)::text || ' admin permissions enabled' as details
from public.role_permissions where role='admin';

select '06_orphan_permissions' as check_name,
  case when count(*) = 0 then 'OK' else 'ORPHAN ROWS FOUND' end as status,
  count(*)::text || ' orphan rows' as details
from public.role_permissions rp
left join public.access_scopes s on s.scope_key=rp.scope_key
where s.scope_key is null;

select '07_branch_modes' as check_name,
  case when count(*) = 0 then 'OK' else 'INVALID BRANCH MODES' end as status,
  count(*)::text || ' invalid rows' as details
from public.role_permissions
where branch_mode not in ('all','assigned','none');

select '08_rls_enabled' as check_name,
  case when count(*) filter (where not relrowsecurity) = 0 and count(*)=5
    then 'OK' else 'RLS CHECK FAILED' end as status,
  count(*) filter (where relrowsecurity)::text || '/5 tables protected' as details
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relname in (
  'access_scopes','role_permissions','user_permission_overrides',
  'user_scope_branches','permission_change_logs'
);

select '09_matrix_by_role' as check_name, role as status,
